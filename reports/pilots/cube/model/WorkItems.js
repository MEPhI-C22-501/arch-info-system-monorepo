cube('WorkItems', {
  sql: 'SELECT * FROM dwh.cube_work_items',
  refreshKey: { every: '1 minute' },
  measures: {
    // *Part measures are additive leaves for the rollups; access.js denies them in user queries.
    tasks: { type: 'count', description: 'Leaf tasks excluding tombstones' },
    plannedSumPart: { sql: `planned_hours`, type: 'sum', shown: false },
    plannedCountPart: { sql: `planned_hours`, type: 'count', shown: false },
    remainingSumPart: { sql: `remaining_hours`, type: 'sum', shown: false },
    remainingCountPart: { sql: `remaining_hours`, type: 'count', shown: false },
    actualSumPart: { sql: `actual_hours`, type: 'sum', shown: false },
    actualCountPart: { sql: `actual_hours`, type: 'count', shown: false },
    completedPart: { sql: `CASE WHEN category='COMPLETED' THEN 1 ELSE 0 END`, type: 'sum', shown: false },
    activePart: { sql: `CASE WHEN category<>'ARCHIVED' THEN 1 ELSE 0 END`, type: 'sum', shown: false },
    estimateDeltaPart: { sql: `CASE WHEN planned_hours>0 AND category='COMPLETED' THEN actual_hours-planned_hours END`, type: 'sum', shown: false },
    estimateBasePart: { sql: `CASE WHEN planned_hours>0 AND actual_hours IS NOT NULL AND category='COMPLETED' THEN planned_hours END`, type: 'sum', shown: false },
    plannedHours: { sql: `CASE WHEN ${plannedCountPart}=${tasks} THEN ${plannedSumPart} END`, type: 'number', description: 'M-02: leaf task plan; null if incomplete' },
    remainingHours: { sql: `CASE WHEN ${remainingCountPart}=${tasks} THEN ${remainingSumPart} END`, type: 'number', description: 'M-03: source remaining hours' },
    actualHours: { sql: `${actualSumPart}`, type: 'number', description: 'Source task actual hours; period time logs use TimeLogs.hours' },
    overrun: { sql: `CASE WHEN ${plannedCountPart}=${tasks} AND ${actualCountPart}=${tasks} AND ${tasks}>0 THEN GREATEST(0,${actualSumPart}-${plannedSumPart}) END`, type: 'number', description: 'Task lifetime overrun; period M-04 uses PlanFact.overrun' },
    overdue: { sql: `CASE WHEN is_overdue=1 THEN 1 ELSE 0 END`, type: 'sum', description: 'M-05: overdue at snapshot observation date' },
    completionPercent: { sql: `100.0*${completedPart}/NULLIF(${activePart},0)`, type: 'number', description: 'M-06: ratio of populations' },
    throughput: { sql: `CASE WHEN completed_at IS NOT NULL THEN 1 ELSE 0 END`, type: 'sum', description: 'M-19: completions; filter completedAt and group ISO week' },
    estimateErrorPercent: { sql: `100.0*${estimateDeltaPart}/NULLIF(${estimateBasePart},0)`, type: 'number', description: 'M-20: weighted estimation error; filter completedAt' },
    // Quantiles are not additive: they are always computed from the facts (ADR-018).
    cycleMedian: { sql: `percentile_cont(0.5) WITHIN GROUP (ORDER BY cycle_days)`, type: 'number', description: 'M-18: median observed cycle days' },
    cycleP85: { sql: `percentile_cont(0.85) WITHIN GROUP (ORDER BY cycle_days)`, type: 'number', description: 'M-18: interpolated percentile' },
    leadMedian: { sql: `percentile_cont(0.5) WITHIN GROUP (ORDER BY lead_days)`, type: 'number', description: 'M-18: median observed lead days' },
    leadP85: { sql: `percentile_cont(0.85) WITHIN GROUP (ORDER BY lead_days)`, type: 'number', description: 'M-18: interpolated percentile' },
    correctionCoefficient: { sql: `percentile_cont(0.5) WITHIN GROUP (ORDER BY CASE WHEN planned_hours>0 AND category='COMPLETED' THEN actual_hours/planned_hours END)`, type: 'number', description: 'M-20: median actual divided by plan' },
  },
  dimensions: {
    id: { sql: `id`, type: 'string', primaryKey: true, shown: true },
    projectId: { sql: `project_id`, type: 'string' },
    userId: { sql: `user_id`, type: 'string' },
    completedAt: { sql: `completed_at::timestamptz`, type: 'time' },
    snapshotDate: { sql: `snapshot_date::date`, type: 'time' },
    iterationId: { sql: `iteration_id`, type: 'string' },
    epicId: { sql: `epic_id`, type: 'string' },
    status: { sql: `category`, type: 'string' },
  },
  preAggregations: {
    // Plan side of the plan-fact view: plan and remaining hours by project.
    byProject: {
      external: false,
      measures: [tasks, plannedSumPart, plannedCountPart, remainingSumPart, remainingCountPart, actualSumPart, actualCountPart,
        completedPart, activePart, overdue, throughput, estimateDeltaPart, estimateBasePart],
      dimensions: [projectId, userId, iterationId, epicId, status],
      refreshKey: { every: '1 minute' },
    },
    completedDaily: {
      external: false,
      measures: [tasks, plannedSumPart, plannedCountPart, actualSumPart, actualCountPart, completedPart, activePart,
        throughput, estimateDeltaPart, estimateBasePart],
      dimensions: [projectId, userId],
      timeDimension: completedAt, granularity: 'day',
      refreshKey: { every: '1 minute' },
    },
  },
});
